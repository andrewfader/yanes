"""Writes tests/stem_reference.hpp from the song corpus's features_ref.json: for each gated group of
records and stem, the quartiles of the features tests/stem_features.hpp measures, over every
excerpt whose stem has them. Only numbers leave the corpus; no audio is copied.

    python3 -I tools/stem_gate_reference.py /path/to/song-corpus/features_ref.json > tests/stem_reference.hpp
"""
import json
import sys

GATED = [('OTC', 'other')]
FEATURES = ['centroid_hz', 'rolloff85_hz', 'hf_share_db', 'corr', 'wobble_cents']


def quantile(values, q):
    """numpy.percentile's default linear interpolation."""
    v = sorted(values)
    at = (len(v) - 1) * q
    low = int(at)
    high = min(low + 1, len(v) - 1)
    return v[low] + (v[high] - v[low]) * (at - low)


def main():
    data = json.load(open(sys.argv[1]))
    out = ['// Generated by tools/stem_gate_reference.py from song-corpus/features_ref.json, measured from the',
           '// user\'s own records (htdemucs_6s stems of 45 s excerpts; see song-corpus/BRIEF.md). Numbers only.',
           '#pragma once', '', '#include <array>', '', 'namespace stem {', '',
           'struct Range { double q25, median, q75; };',
           'struct Reference {',
           '  const char* group;',
           '  const char* stem;',
           '  int tracks;',
           '  Range %s;' % ', '.join(FEATURES),
           '};', '',
           'inline constexpr std::array kReferences{']
    for group, stem in GATED:
        rows = [v[stem] for k, v in sorted(data.items()) if k.startswith(group + '_') and stem in v]
        ranges = []
        for f in FEATURES:
            xs = [r[f] for r in rows if r.get(f) is not None]
            ranges.append('{%.4g, %.4g, %.4g}' % (quantile(xs, 0.25), quantile(xs, 0.5), quantile(xs, 0.75)))
        out.append('    Reference{"%s", "%s", %d, %s},' % (group, stem, len(rows), ', '.join(ranges)))
    out += ['};', '', '}  // namespace stem', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
