SCENARIO(zzz_coverage_check_runs_last) {
  GIVEN("the coverage registry built by the previous scenarios");
  std::set<std::string> param_names_covered;
  for (const auto& e : coverage::all())
    if (e.surface == "control" || e.surface == "knob" || e.surface == "toggle"
        || e.surface == "lane" || e.surface == "segment" || e.surface == "strip"
        || e.surface == "menu" || e.surface == "preset" || e.surface == "waveform")
      param_names_covered.insert(e.name);
  WHEN("we check every parameter is represented");
  for (size_t i = 0; i < P::kParamCount; ++i) {
    CHECK(param_names_covered.count(P::kSpecs[i].name) > 0,
          std::string("no scenario touched parameter: ") + P::kSpecs[i].name);
  }
  THEN("no parameter is left untested by the E2E walk");
}

// ===========================================================================
//  Entry point
// ===========================================================================

int main(int argc, char** argv) {
  if (argc < 2) {
    std::fprintf(stderr, "Usage: %s <path_to_YANES.clap> [coverage_output_path]\n", argv[0]);
    return 1;
  }
  g_clap_path = argv[1];
  const std::string cov_path = argc >= 3 ? argv[2] : "bdd_coverage.md";

  std::printf("================================================================\n");
  std::printf("YANES BDD end-to-end coverage suite\n");
  std::printf("CLAP plug-in: %s\n", g_clap_path);
  std::printf("================================================================\n");

  // Sort and run scenarios.
  std::vector<bdd::Entry> entries = bdd::registry();
  std::sort(entries.begin(), entries.end(),
            [](const bdd::Entry& a, const bdd::Entry& b) {
              return std::strcmp(a.name, b.name) < 0;
            });
  for (auto& e : entries) {
    bdd::Scenario s;
    bdd::g_scenario = &s;
    std::printf("\nScenario: %s\n", e.name);
    s.begin(e.name);
    e.fn();
    if (s.failed) ++bdd::g_failed; else ++bdd::g_passed;
    bdd::g_scenario = nullptr;
  }

  std::printf("\n================================================================\n");
  std::printf("Scenarios: %d passed, %d failed\n", bdd::g_passed, bdd::g_failed);
  std::printf("================================================================\n");

  int missing = 0;
  coverage::dump(cov_path, &missing);
  std::printf("Coverage matrix written to %s (%zu entries, %d parameter(s) uncovered)\n",
              cov_path.c_str(), coverage::all().size(), missing);

  return (bdd::g_failed == 0 && missing == 0) ? 0 : 1;
}
