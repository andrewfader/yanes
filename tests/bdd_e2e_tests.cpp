// BDD-style end-to-end coverage of the entire YANES UI.
//
// Every knob, preset, option, button, and config in the editor is exercised through a
// Given/When/Then scenario that drives real audio. The suite has four layers:
//
//   Unit        pure parameter-table self-tests (defaults, ranges, value-to-text, parse round-trip)
//   Integration per-parameter CLAP process() checks with real audio output
//   System      full E2E editor walks: page navigation, every preset, every widget gesture
//   Coverage    a coverage matrix printed at the end that fails if any control is untested
//
// The editor runs through ui_editor.hpp's C++ API; every parameter edit is also pushed
// through the real clap_plugin_params_t and rendered into audio buffers we measure.

