class EditorMirror final : public EditorHost {
 public:
  EditorMirror(const clap_plugin_t* plugin) : plugin_(plugin) {
    for (size_t i = 0; i < P::kParamCount; ++i) {
      values_[i] = P::kSpecs[i].def;
      pending_[i] = P::kSpecs[i].def;
    }
    refresh();
  }

  int param_count() const override { return static_cast<int>(P::kParamCount); }
  ParamInfo info(int id) const override {
    const auto& s = P::kSpecs[id];
    return {s.name, s.min, s.max, s.def, s.stepped};
  }
  double value(int id) const override { return values_[id]; }

  void begin_edit(int id) override {
    CHECK(id >= 0 && id < param_count(), "begin_edit out of range");
    pending_[id] = values_[id];
  }
  void edit(int id, double v) override {
    const auto& s = P::kSpecs[id];
    if (v < s.min - 1e-9 || v > s.max + 1e-9) {
      bdd::scenario_fail("edit out of range for " + std::string(s.name));
      return;
    }
    if (s.stepped && v != std::round(v)) {
      bdd::scenario_fail("stepped param got non-integer: " + std::string(s.name));
      return;
    }
    pending_[id] = v;
  }
  void end_edit(int id) override {
    values_[id] = pending_[id];
    set_param(plugin_, static_cast<clap_id>(id), pending_[id]);
  }
  void format(int id, double v, char* out, size_t n) const override {
    P::format_value(static_cast<uint32_t>(id), v, out, static_cast<uint32_t>(n));
  }
  const char* short_label(int id) const override {
    const char* n = yanes_short_name(id);
    return n ? n : P::kSpecs[id].name;
  }
  int size_percent() const override { return percent_; }
  void request_size(int p) override { percent_ = p; }

  void refresh() {
    const auto* params = params_of(plugin_);
    for (uint32_t i = 0; i < params->count(plugin_); ++i) {
      clap_param_info_t pi{};
      assert(params->get_info(plugin_, i, &pi));
      double v = 0.0;
      assert(params->get_value(plugin_, pi.id, &v));
      values_[pi.id] = v;
      pending_[pi.id] = v;
    }
  }

  void reset_value(int id) {
    values_[id] = P::kSpecs[id].def; pending_[id] = P::kSpecs[id].def;
    set_param(plugin_, static_cast<clap_id>(id), P::kSpecs[id].def);
  }

 private:
  const clap_plugin_t* plugin_;
  std::array<double, P::kParamCount> values_{};
  std::array<double, P::kParamCount> pending_{};
  int percent_ = 100;  // default 100% so the SIZE button is visible by default
};

