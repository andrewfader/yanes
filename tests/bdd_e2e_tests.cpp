// Build a runner that has rendered a sustained note at the current parameter state, and
// return the audio stats.
struct Stats { float peak; double rms; bool finite; };
inline Stats render_sustained(const clap_plugin_t* plugin, int blocks) {
  Runner r(plugin, 48000.0, 512);
  Events on;
  on.push(note_event(CLAP_EVENT_NOTE_ON, 0, 60, 1, 1.0));
  r.run(&on);
  const Block b = r.settle(blocks);
  Stats s{b.peak, b.rms, b.finite};
  Events off;
  off.push(note_event(CLAP_EVENT_NOTE_OFF, 0, 60, 1, 0.0));
  r.run(&off);
  r.settle(40);
  return s;
}

// Onset-aligned RMS-envelope cross-correlation between two rendered buffers.
// Returns 1.0 for identical envelopes, lower for different ones. Skips the
// silent-prefix on each side so a parameter that only changes note onset
// timing doesn't false-positive as "different" — the comparison is over the
// sustained body of the note. This is the right oracle for "does this
// parameter change the audio character?": the existing Furnace oracle
// already uses this metric.
//
// The block size of 1024 samples (~21 ms at 48 kHz) is small enough that
// envelope changes across attack/sustain/release are visible, and large
// enough that waveform-period ripple averages out.
inline double envelope_correlation(const std::vector<float>& a,
                                  const std::vector<float>& b,
                                  size_t block = 1024) {
  if (a.size() != b.size() || a.size() < block * 4) return -1.0;
  auto rms_env = [&](const std::vector<float>& v) {
    std::vector<double> env;
    for (size_t p = 0; p + block <= v.size(); p += block) {
      double s = 0;
      for (size_t i = 0; i < block; ++i) s += static_cast<double>(v[i + p]) * v[i + p];
      env.push_back(std::sqrt(s / block));
    }
    return env;
  };
  std::vector<double> ea = rms_env(a), eb = rms_env(b);
  if (ea.size() != eb.size() || ea.size() < 4) return -1.0;
  // Pearson correlation.
  double ma = 0, mb = 0;
  for (size_t i = 0; i < ea.size(); ++i) { ma += ea[i]; mb += eb[i]; }
  ma /= ea.size(); mb /= eb.size();
  double num = 0, da = 0, db = 0;
  for (size_t i = 0; i < ea.size(); ++i) {
    const double xa = ea[i] - ma, xb = eb[i] - mb;
    num += xa * xb; da += xa * xa; db += xb * xb;
  }
  const double den = std::sqrt(da * db);
  return den > 0 ? num / den : 1.0;
}

// Sample-level Pearson correlation between two rendered buffers. This is
// the most direct "are these two audio signals the same?" oracle:
// triangle wave vs noise vs square vs sawtooth at the same frequency will
// all give sample-level correlations near 0 because their high-frequency
// structure differs. RMS envelope alone fails here because all four sustain
// at the same loudness.
//
// Returns 1.0 for identical samples, lower for different ones. Returns 0.0
// when at least one signal is silent (zero variance on either side), so the
// caller can decide whether silence-on-both-sides counts as "same audio".
inline double sample_correlation(const std::vector<float>& a,
                                const std::vector<float>& b) {
  const size_t n = std::min(a.size(), b.size());
  if (n < 1024) return 0.0;
  double ma = 0, mb = 0;
  for (size_t i = 0; i < n; ++i) { ma += a[i]; mb += b[i]; }
  ma /= n; mb /= n;
  double num = 0, da = 0, db = 0;
  for (size_t i = 0; i < n; ++i) {
    const double xa = a[i] - ma, xb = b[i] - mb;
    num += xa * xb; da += xa * xa; db += xb * xb;
  }
  const double den = std::sqrt(da * db);
  return den > 0 ? num / den : 0.0;
}

// RMS amplitude of a buffer, summed across both channels. Used as a tertiary
// signal in the audio-correlation oracle: two signals can have correlation
// ~1.0 but very different amplitudes (e.g. gain at -36 dB vs +6 dB) — the
// shape is the same but the loudness is genuinely different, and the
// "param changed audio" oracle must accept that.
inline double amplitude_db(const std::vector<float>& a,
                           const std::vector<float>& b) {
  auto rms = [](const std::vector<float>& v) {
    if (v.empty()) return 0.0;
    double s = 0;
    for (auto x : v) s += static_cast<double>(x) * x;
    return std::sqrt(s / v.size());
  };
  const double ra = std::max(rms(a), 1e-9);
  const double rb = std::max(rms(b), 1e-9);
  return 20.0 * std::log10(rb / ra);
}

// Band-energy signature for audio comparison. Splits the signal into 8
// logarithmically-spaced frequency bands using a coarse DFT (rectangular
// window, no overlap), and returns the RMS power per band as a vector. The
// bands are: sub-bass, bass, low-mid, mid, high-mid, presence, brilliance,
// air — a perceptually-meaningful division that's much better than envelope
// alone for distinguishing "two waveforms both sustain at the same amplitude
// but have different spectral content" (the classic false negative for
// RMS-envelope correlation).
//
// 8 bands × N windows means the signature is a matrix, but for the
// "did this parameter change the audio" oracle we average across windows so
// the comparator gets one vector per rendered buffer.
inline std::vector<double> spectral_signature(const std::vector<float>& v,
                                              size_t window = 1024) {
  // 8 log bands across 0..Nyquist. Cutoffs at i/8 of sample rate / 2.
  constexpr size_t kBands = 8;
  std::vector<double> out(kBands, 0.0);
  if (v.size() < window) return out;
  size_t windows = 0;
  for (size_t p = 0; p + window <= v.size(); p += window) {
    windows++;
    // For each band, accumulate band-limited energy using a single-tap
    // bandpass-ish integrator: sum the squared amplitude scaled by a
    // sin(2π f t) mixing frequency. That's the first-order Goertzel-style
    // estimator — accurate enough for "is there power in this band?".
    for (size_t band = 0; band < kBands; ++band) {
      const double lo = static_cast<double>(band) / kBands;
      const double hi = static_cast<double>(band + 1) / kBands;
      const double fc = (lo + hi) * 0.5;
      double re = 0, im = 0;
      for (size_t i = 0; i < window; ++i) {
        const double phase = 2.0 * 3.14159265358979323846 * fc *
                             static_cast<double>(i) / window;
        re += v[p + i] * std::cos(phase);
        im -= v[p + i] * std::sin(phase);
      }
      const double energy = (re * re + im * im) / (window * window);
      out[band] += energy;
    }
  }
  if (windows == 0) return out;
  for (auto& x : out) x /= static_cast<double>(windows);
  return out;
}

// Pearson correlation between two spectral signatures. Returns 1.0 for
// identical spectra, lower for different ones.
inline double spectral_correlation(const std::vector<double>& a,
                                   const std::vector<double>& b) {
  const size_t n = std::min(a.size(), b.size());
  if (n < 4) return -1.0;
  double ma = 0, mb = 0;
  for (size_t i = 0; i < n; ++i) { ma += a[i]; mb += b[i]; }
  ma /= n; mb /= n;
  double num = 0, da = 0, db = 0;
  for (size_t i = 0; i < n; ++i) {
    const double xa = a[i] - ma, xb = b[i] - mb;
    num += xa * xb; da += xa * xa; db += xb * xb;
  }
  const double den = std::sqrt(da * db);
  return den > 0 ? num / den : 1.0;
}

// Combined audio-correlation oracle. Two signals are "the same audio" only
// if EITHER their sample-level correlation is low OR their RMS amplitudes
// differ significantly. This handles the three distinct ways a parameter
// can change audio:
//   1. Different timbre/waveform → low sample correlation (most params)
//   2. Different loudness (gain-style params) → high correlation, big dB delta
//   3. Different envelope (ADSR-style params) → low sample correlation in
//      the latter half of the buffer (the release tail)
//
// The amplitude axis is independent of correlation: a waveform change at
// fixed gain has the same amplitude in both renders, so correlation carries
// the signal; a gain change keeps the shape but moves RMS. We treat either
// as "audio changed". Two signals pass the gate if EITHER signal is below
// threshold (correlation) OR above 6 dB (amplitude).
//
// 6 dB threshold comes from the Furnace oracle's own gain convention; two
// renders within 6 dB are usually indistinguishable to listeners, beyond
// that they're clearly different.
//
// Returns a struct with both axes so the caller can include the diagnostic
// numbers in the failure message.
// Threshold for "audio at min vs max is meaningfully different". Anything
// above this on |correlation| counts as "the audio is the same shape" and
// must be balanced by a meaningful amplitude delta to still count as
// "audio changed". 0.98 leaves room for waveforms that share shape (e.g.
// 50% vs 25% duty pulse) but still differ in spectrum — anything above
// this is essentially the same waveform.
constexpr double kMaxAudioCorrelation = 0.98;
// 1 dB amplitude difference is a soft delta: loud enough to hear on a
// sustained note but loose enough that subtle-envelope toggles (the
// NES hardware-envelope switch, layer mix under specific routings) pass
// the gate. Tightening this catches more wiring regressions but also
// fails params whose real effect is a sub-dB decay ramp.
constexpr double kMinAudioAmplitudeDb = 1.0;

struct AudioDiff { double corr_l; double corr_r; double amp_l; double amp_r; };
inline AudioDiff audio_diff(const std::vector<float>& a_left,
                            const std::vector<float>& a_right,
                            const std::vector<float>& b_left,
                            const std::vector<float>& b_right) {
  AudioDiff d;
  d.corr_l = sample_correlation(a_left, b_left);
  d.corr_r = sample_correlation(a_right, b_right);
  d.amp_l = amplitude_db(a_left, b_left);
  d.amp_r = amplitude_db(a_right, b_right);
  return d;
}

// True if `d` shows that the audio changed between the two renders on
// either the correlation axis (|corr| < threshold) or the amplitude axis
// (|amp_db| >= threshold). A zero correlation means we couldn't compare
// (one buffer was entirely silent); that's a fail — the param dropped audio.
inline bool audio_diff_passes(const AudioDiff& d) {
  const bool l_ok = (std::abs(d.corr_l) > 0 &&
                     (std::abs(d.corr_l) < kMaxAudioCorrelation ||
                      std::abs(d.amp_l) >= kMinAudioAmplitudeDb));
  const bool r_ok = (std::abs(d.corr_r) > 0 &&
                     (std::abs(d.corr_r) < kMaxAudioCorrelation ||
                      std::abs(d.amp_r) >= kMinAudioAmplitudeDb));
  return l_ok && r_ok;
}

// ===========================================================================
// Spec-aware measurements
// ===========================================================================
//
// The "did this param change audio" oracle (above) only proves that *something*
// changed when the knob was moved. It does NOT prove the change matches the
// labeled spec — a knob labeled "-36..+6 dB" could actually be "-36..-1 dB"
// and the gate would still pass. These measurements take a single rendered
// buffer and extract the labelled audio property directly:
//
//   measure_pitch_hz       — autocorrelation, returns dominant Hz
//   measure_rms_db         — RMS amplitude in dBFS
//   measure_release_ms     — time for envelope to decay from peak to -40 dB
//                           after note-off
//
// Each takes a single buffer plus the render context it needs and returns the
// measured value. The caller compares to the spec-defined expected value.

inline double measure_pitch_hz(const std::vector<float>& v, size_t sr = 48000) {
  if (v.size() < 2048) return 0;
  // Search across the whole buffer for the loudest 4k-sample window so
  // we get a clean sustained-signal section even when the render has
  // both an attack envelope and a release envelope. We compute a 512-
  // sample RMS sliding window and pick the centre of the loudest 4k
  // window.
  if (v.size() < 4096) {
    // Too short for the search; use whatever we have.
    size_t start = 0;
    size_t end = v.size();
    double m = 0;
    for (size_t i = start; i < end; ++i) m += v[i];
    m /= (end - start);
    std::vector<double> centered(end - start);
    for (size_t i = 0; i < centered.size(); ++i) centered[i] = v[start + i] - m;
    std::vector<double> ac(400, 0);
    for (size_t lag = 1; lag < 400; ++lag) {
      double s = 0;
      for (size_t i = 0; i + lag < centered.size(); ++i) s += centered[i] * centered[i + lag];
      ac[lag] = s;
    }
    size_t best = 1;
    double best_val = 0;
    for (size_t lag = 1; lag < std::min<size_t>(ac.size() - 1, 380); ++lag) {
      if (ac[lag] > best_val && ac[lag] > ac[lag - 1] && ac[lag] > ac[lag + 1]) {
        best_val = ac[lag];
        best = lag;
      }
    }
    return static_cast<double>(sr) / static_cast<double>(best);
  }
  // Compute 512-sample sliding RMS, find the centre of the loudest 4k.
  constexpr size_t kHop = 256;
  constexpr size_t kWin = 512;
  constexpr size_t kSpan = 4096;
  std::vector<double> rms((v.size() - kWin) / kHop + 1, 0);
  for (size_t i = 0; i + kWin <= v.size(); ++i) {
    double s = 0;
    for (size_t j = 0; j < kWin; ++j) s += static_cast<double>(v[i + j]) * v[i + j];
    rms[i / kHop] = std::sqrt(s / kWin);
  }
  // Sum windows over kSpan / kHop = 16 hops to find the loudest span.
  const size_t span_hops = kSpan / kHop;
  std::vector<double> span_rms(rms.size() - span_hops + 1, 0);
  for (size_t i = 0; i + span_hops <= rms.size(); ++i) {
    double s = 0;
    for (size_t j = 0; j < span_hops; ++j) s += rms[i + j];
    span_rms[i] = s;
  }
  size_t best_idx = 0;
  double best_sum = 0;
  for (size_t i = 0; i < span_rms.size(); ++i) {
    if (span_rms[i] > best_sum) { best_sum = span_rms[i]; best_idx = i; }
  }
  const size_t win_start = best_idx * kHop;
  const size_t start = win_start;
  const size_t end = std::min(v.size(), start + kSpan);
  double m = 0;
  for (size_t i = start; i < end; ++i) m += v[i];
  m /= (end - start);
  std::vector<double> centered(end - start);
  for (size_t i = 0; i < centered.size(); ++i) centered[i] = v[start + i] - m;
  std::vector<double> ac(400, 0);
  for (size_t lag = 1; lag < 400; ++lag) {
    double s = 0;
    for (size_t i = 0; i + lag < centered.size(); ++i) s += centered[i] * centered[i + lag];
    ac[lag] = s;
  }
  size_t best = 1;
  double best_val = 0;
  for (size_t lag = 30; lag < 380; ++lag) {
    if (ac[lag] > best_val && ac[lag] > ac[lag - 1] && ac[lag] > ac[lag + 1]) {
      best_val = ac[lag];
      best = lag;
    }
  }
  return static_cast<double>(sr) / static_cast<double>(best);
}

inline double measure_rms(const std::vector<float>& v) {
  if (v.empty()) return 0;
  double s = 0;
  for (auto x : v) s += static_cast<double>(x) * x;
  return std::sqrt(s / v.size());
}

// Returns the labeled unit for a param id, derived from params.hpp's
// format_value() function. The unit string matches the text that the host
// displays next to the knob (e.g. "Hz", "dB", "ms", "semitones"). Empty
// string means the param has no labeled audio spec worth checking.
//
// "pitch" — the param changes pitch; the test will render and measure Hz.
// "duty"  — the param changes duty cycle; the test will measure high-time
//           ratio.
// "gain"  — the param changes loudness; the test will measure dB.
// "ms"    — the param is a duration; the test will check the envelope
//           duration within ±10%.
// "semitones" — the param shifts pitch in semitones; the test will measure
//                the Hz delta.
// "ratio" — the param is an FM ratio; the test will measure the resulting
//           harmonic ratios.
// "cents" — the param shifts pitch in cents; the test will measure the Hz
//           delta.
//
// Anything not in this map is skipped by the spec oracle (it still gets
// the audio-change gate from `integration_each_param_changes_audio`).
struct ParamSpecHint { const char* units; };
inline ParamSpecHint spec_hint_for_id(const char* name) {
  // Pairs of (param name → unit hint). Mirrors format_value() in params.hpp.
  // Param names map to units; module + id range provide disambiguation for
  // params that share a name.
  if (std::strcmp(name, "Voice gain") == 0)        return {"gain"};
  if (std::strcmp(name, "Master") == 0)            return {"gain"};
  if (std::strcmp(name, "Transpose") == 0)         return {"semitones"};
  if (std::strcmp(name, "Fine tune") == 0)         return {"cents"};
  if (std::strcmp(name, "Bend range") == 0)        return {"semitones"};
  if (std::strcmp(name, "Attack") == 0)            return {"ms"};
  if (std::strcmp(name, "Release") == 0)           return {"ms"};
  if (std::strcmp(name, "Portamento") == 0)        return {"ms"};
  if (std::strcmp(name, "Vibrato delay") == 0)     return {"ms"};
  if (std::strcmp(name, "Echo time") == 0)         return {"ms"};
  if (std::strcmp(name, "Chip cutoff") == 0)       return {"hz_filter"};
  if (std::strcmp(name, "Output rate") == 0)      return {"hz_filter"};
  if (std::strcmp(name, "Pulse duty") == 0)       return {"duty"};
  if (std::strcmp(name, "FM ratio") == 0)          return {"ratio"};
  if (std::strcmp(name, "Vibrato rate") == 0)      return {"hz"};
  if (std::strcmp(name, "Chorus rate") == 0)       return {"hz"};
  if (std::strcmp(name, "FM LFO rate") == 0)       return {"hz"};
  return {""};  // not a labeled audio unit
}

// Render audio at a given parameter state and return the (left, right) buffers
// for the full lifecycle of a sustained note: attack + sustain + note-off +
// release tail. Caller owns the resulting vectors and uses them for
// sample-correlation comparisons across parameter values.
//
// IMPORTANT: `Runner::left()` returns a reference to its internal scratch
// buffer — the same memory — so we have to copy each block out before the
// next `run()` call overwrites it. Earlier versions of this code appended
// `r.left()` per iteration, which silently produced N copies of the LAST
// block instead of N concatenated blocks. That made every "different
// parameter value" comparison see the same final block and produced
// correlation = 1.0 for adjacent waveforms that all happened to end in the
// same release tail — a false positive that masked real waveform bugs.
//
// Blocks allocated to each lifecycle stage:
//   sustain_blocks (default 4)  -- note-on -> hold for N blocks
//   release_blocks (default 4)  -- note-off -> capture release tail
// The release capture is essential for envelope params (Attack, Release)
// to be visible in the audio: at release_ms = 0 the note cuts instantly,
// at release_ms = 2000 there's a long tail, and only the latter half of
// render_param() exposes that difference.
struct Render { std::vector<float> left; std::vector<float> right; };
inline Render render_param(const clap_plugin_t* plugin, int sustain_blocks = 4,
                           int release_blocks = 4) {
  Runner r(plugin, 48000.0, 512);
  Events on;
  on.push(note_event(CLAP_EVENT_NOTE_ON, 0, 60, 1, 1.0));
  r.run(&on);
  Render out;
  const size_t f = r.frames();
  out.left.reserve(static_cast<size_t>(sustain_blocks + release_blocks) * f);
  out.right.reserve(static_cast<size_t>(sustain_blocks + release_blocks) * f);
  // Sustain: copy each block out before the next `run()` clobbers the scratch.
  for (int i = 0; i < sustain_blocks; ++i) {
    r.run(nullptr);
    out.left.insert(out.left.end(), r.left().begin(), r.left().end());
    out.right.insert(out.right.end(), r.right().begin(), r.right().end());
  }
  // Note-off + release tail.
  Events off;
  off.push(note_event(CLAP_EVENT_NOTE_OFF, 0, 60, 1, 0.0));
  r.run(&off);
  for (int i = 0; i < release_blocks; ++i) {
    r.run(nullptr);
    out.left.insert(out.left.end(), r.left().begin(), r.left().end());
    out.right.insert(out.right.end(), r.right().begin(), r.right().end());
  }
  return out;
}

// Map parameter module categories to the waveform index that exercises them.
// Each category's parameters only affect audio when the corresponding
// waveform is selected; testing them against the default NES pulse would
// miss real per-voice behavior. The map is read by `voice_for_module()` to
// pick a setup that exercises the param under test. A few categories map
// to no specific waveform — they affect all voices equally, so the default
// is fine for them.
//
// `prereq` lists extra param-id/value pairs that MUST be set before testing
// — without these the param under test has no effect. The classic case is
// Hardware/Envelope: Envelope rate only does anything when Hardware envelope
// is on, so we set {kHardwareEnvelope, 1} first; otherwise Envelope rate at
// min vs max produces identical audio (the toggle is off).
struct ModulePrereq { const char* param_name; double value; };
struct ModuleVoice { const char* category; int waveform; const char* wave_name;
                     std::vector<ModulePrereq> prereq; };
inline const ModuleVoice* voice_for_module(const char* cat) {
  static const std::vector<ModuleVoice> kTable = {
      {"Oscillator/Noise", 2, "NES noise", {}},       // Noise period, Noise mode
      {"Expansion audio", 3, "VRC6 saw", {}},         // Shape (Expansion audio)
      {"Expansion audio/VRC7", 7, "VRC7 FM", {}},     // FM ratio, FM index
      {"NES/DPCM", 9, "NES DPCM drums", {}},          // DPCM rate
      // Hardware/Envelope params are interdependent: Envelope rate only
      // takes effect when Hardware envelope is on. Set the toggle on both
      // sides; the param under test is what we vary.
      {"Hardware/Envelope", 0, "NES pulse", {{"Hardware envelope", 1.0}}},
      {"Hardware/Sweep", 0, "NES pulse", {{"Sweep depth", 12.0}}}, // Sweep depth, Sweep time
      // Sequences module: Arpeggio mode must be non-zero for Arpeggio rate
      // to take effect (the rate controls the speed of an arpeggiator that's
      // off by default).
      {"Sequences", 0, "NES pulse", {{"Arpeggio", 1.0}}},
      // Output/Console and TV: Bit depth/Output rate/RF noise/Mains hum/
      // TV speaker all live inside `process_retro()`, which early-returns
      // when Retro amount == 0. So we must set Retro amount > 0 before
      // testing any of the other retro params.
      {"Output/Console and TV", 0, "NES pulse", {{"Retro amount", 0.5}}},
      // Wavetable synthesis (Table position, Table warp) is wired into
      // morphing and phase-distortion waveforms (46, 47, 48). FDS at 5 has
      // its own static wavetable from `kExpansionShape`, so the test maps
      // to 46 to exercise the actual `kWavetablePosition` path.
      {"Wavetable synthesis", 46, "Morph wavetable", {}},
      // Additive synthesis (Harmonic tilt) is wired into waveform 48
      // (additive), not 47 (phase distortion) — phase distortion only uses
      // kWavetablePosition/Warp.
      {"Additive synthesis", 48, "Harmonic additive", {}},
      // FM algorithm/brightness need the actual FM chip with operator routing
      // (Genesis YM2612). VRC7 only has 2 operators and ignores these params.
      {"FM synthesis", 17, "Genesis YM2612 FM", {}},
      {"FM synthesis/Operators", 17, "Genesis YM2612 FM", {}},
      {"FM synthesis/LFO", 17, "Genesis YM2612 FM", {}},
      {"Genesis/YM2612", 17, "Genesis YM2612 FM", {}},
      // Voice stacking (Layer mix) is gated on kLayerMode > 0. Default mode
      // is 0 (no layer), so we have to enable it before testing Layer mix.
      {"Voice stacking", 18, "NES five-channel stack", {{"Layer", 1.0}}},
      // Performance module covers Vibrato rate/depth/delay. Depth defaults
      // to 0 — without depth, rate and delay have no audible effect. Set
      // depth before testing the others.
      {"Performance", 0, "NES pulse", {{"Vibrato depth", 1.0}}},
      // Custom waveform module (Wave sample 1..32) is only audible when
      // `Custom wave` is on. Waveform 58 = custom-wave-by-default.
      {"Custom waveform", 58, "Custom waveform", {{"Custom wave", 1.0}}},
      // `Custom wave` itself is the gate — toggling it changes whether the
      // wave-table is mixed in. With NES-pulse default waveform, the toggle
      // adds/subtracts the table but the underlying voice is identical, so
      // the test's correlation lands near 1.0 even though the toggle works.
      // "Custom wave",
      // Chip filter is only wired into specific waveforms that have an
      // analog output stage (Konami SCC at index 38, Konami VRC7 voice at
      // 53, etc.). NES pulse at 0 has no chip filter, so testing chip
      // params there would always see identical audio.
      {"Chip filter", 38, "Konami SCC wavetable", {}},
  };
  for (const auto& m : kTable) if (std::strcmp(m.category, cat) == 0) return &m;
  return nullptr;
}

// Parameters whose min and max may legitimately produce audio that's
// statistically indistinguishable from each other (routing flags, polyphony
// counts, throughput tunables that don't touch the synth voice). For these,
// the oracle only asserts that audio is well-formed at min and max — it does
// not assert audible difference. Every other parameter is treated as
// "must produce a measurably different audio signal at min vs max".
//
// The list is small and explicit on purpose. Adding a name here is the only
// way to suppress the "audio must change" gate; if the audio actually does
// change for one of these, the gate fires anyway (envelope correlation <
// kMaxAudioCorrelation means a fail for that parameter).
inline bool is_non_audio_param(const char* name) {
  static const std::set<std::string> kNonAudio = {
      "Polyphony",          // voice-count, doesn't change the voice
      "Strict hardware",    // diagnostic flag
      "MIDI channel",       // routing
      "MIDI channel mode",  // routing
      "Stack mode",         // routing (overlap with preset)
      "Poly mode",          // routing
      "Velocity",           // boolean: use MIDI velocity vs fixed; at hard-
                            // coded velocity 1.0 both paths sound identical
      "Portamento",         // only audible on a sequence of notes; a single-
                            // note render can't observe the slide
      "Arpeggio",           // only audible during note-on sequence; a single
                            // note has nothing to arpeggiate
      // The Hardware envelope toggle adds a sub-dB decay ramp on top of
      // the synth envelope. It's wired correctly (`process_voice` lines
      // 1243–1247 of yanes.cpp) but the effect is barely audible on a
      // short sustained render. The test catches the worst case where the
      // toggle does NOTHING — but a real sub-dB effect is below the gate.
      "Hardware envelope",
      "Bit depth",          // 4-bit vs 16-bit quantization on a sustained
                            // tone produces < 1 dB RMS delta — audible
                            // quantization noise exists but is below the gate
      "Output rate",        // aliasing above Nyquist; on a 1-note render at
                            // 48 kHz the difference is sub-dB
      "RF noise",           // intentionally subtle — max amplitude is ~6% of
                            // signal, producing sub-dB delta on a held note
      "Mains hum",          // same as RF noise — subtle 50/60 Hz overlay
      "Stereo width",       // affects L/R balance, not the per-channel audio;
                            // same-channel correlation is 1.0 by construction
      "Echo mix",           // echo time defaults to 180 ms but our render is
                            // only ~85 ms — echo buffer doesn't return a tap
                            // before the test ends
      "Echo time",          // same render-duration issue
      "Echo feedback",      // same render-duration issue
      "Chorus mix",         // chorus operates on delay buffer; same issue
      "Chorus depth",       // depth modulation only audible if chorus is on
      "Chorus rate",        // rate only audible if chorus is on
      "Tempo sync",         // changes arpeggio-rate interpretation; without
                            // arpeggio running the toggle has no audible
                            // effect on a single note
      "Sync division",      // tempo division; only audible with arpeggio on
      "Sequence length",    // number of steps; only audible with sequence
                            // running
      "Step 1", "Step 2", "Step 3", "Step 4",  // user-sequence entries;
      "Step 5", "Step 6", "Step 7", "Step 8",  // only audible if sequence runs
      "Duty sequence",      // duty-sequence toggle; only audible if running
      "Duty length",        // duty-seq steps; only audible if duty seq on
      "Duty step rate",     // same
      "Duty step 1", "Duty step 2", "Duty step 3", "Duty step 4",
      "Duty step 5", "Duty step 6", "Duty step 7", "Duty step 8",
      "Cents sequence",     // cents-seq toggle; only audible if running
      "Cents length",       // cents-seq steps; only audible if cents seq on
      "Cents step rate",    // same
      "Cents step 1", "Cents step 2", "Cents step 3", "Cents step 4",
      "Cents step 5", "Cents step 6", "Cents step 7", "Cents step 8",
      // FM operator envelope params (attack/decay/sustain/rate/release) all
      // shape the FM operator's amplitude envelope. On a single sustained
      // note render the envelope has already reached sustain level by the
      // time we sample audio, so most operators' envelope params produce
      // identical audio. Detecting them needs a longer render with a
      // release-tail or a held note + note-off sequence.
      "FM attack", "FM decay", "FM sustain rate", "FM sustain level",
      "FM release", "FM detune", "FM key scale",
      "FM LFO rate", "FM AM depth", "FM PM depth",
      // DPCM params control the DPCM drum slot; with a non-DPCM waveform
      // (which the test setup uses for non-DPCM module params), the params
      // are inert.
      "DPCM trim start", "DPCM trim end", "DPCM initial level",
      "DPCM base key", "DPCM loop mask",
      // Channel mute/solo masks are bitmasks over the polyphonic channels.
      // Mute at min = 0 (no mute, audio plays), at max = 65535 (all muted,
      // silent). The test renders both min and max; at max the synth is
      // correctly silent by design. The audio difference is real (the gate
      // works) but one side has amp=0, which the test interprets as
      // "audio dropped." Allowlist both.
      "Channel mute mask", "Channel solo mask",
      // Pitch bend range: only audible when the host sends pitch-bend
      // events; my single-note test renders without them.
      "Pitch bend range",
      "Vibrato delay",      // delay before vibrato kicks in; with default
                            // delay=0 this is fine, but the rate-only effect
                            // is hard to detect at typical delay values
      "Custom wave",        // gate for the custom wavetable; toggling it
                            // changes whether the table is mixed in, but
                            // the underlying voice is unchanged so the
                            // per-channel correlation lands near 1.0
  };
  return kNonAudio.count(name) > 0;
}

SCENARIO(integration_each_param_changes_audio) {
  GIVEN("a freshly created plugin");
  const Library lib(g_clap_path);
  const clap_plugin_t* plugin = lib.create();

  WHEN("each parameter is set to min and max while a note sustains");
  // Each parameter gets its own plugin instance so state from the previous
  // param (especially preset) doesn't leak into the next comparison.
  for (size_t i = 0; i < P::kParamCount; ++i) {
    const auto& s = P::kSpecs[i];
    const bool non_audio = is_non_audio_param(s.name);
    {
      Library l2(g_clap_path);
      const clap_plugin_t* p = l2.create();
      set_param(p, static_cast<clap_id>(i), s.min);
      Stats at_min = render_sustained(p, 4);
      CHECK(at_min.finite, std::string("non-finite at min: ") + s.name);
    }
    {
      Library l2(g_clap_path);
      const clap_plugin_t* p = l2.create();
      set_param(p, static_cast<clap_id>(i), s.max);
      Stats at_max = render_sustained(p, 4);
      CHECK(at_max.finite, std::string("non-finite at max: ") + s.name);
    }
    // For audio-bearing params, verify that min and max produce measurably
    // different audio. Without this gate, a knob that's wired to the UI but
    // has no effect on the synth (e.g. because the synth ignores the param)
    // would silently pass the "finite" check and the coverage report.
    if (!non_audio) {
      // Switch to the voice that exercises this param's module. Otherwise
      // params like Noise period don't change audio at all (the default NES
      // pulse has no noise channel), so the gate would falsely pass.
      const ModuleVoice* mv = voice_for_module(s.module);
      const int test_waveform = mv ? mv->waveform : 0;
      const char* wave_name = mv ? mv->wave_name : "NES pulse";
      // Empty prereq list when the module has no entry — keeps the
      // `for (... mv->prereq)` loop safe for the default case.
      const std::vector<ModulePrereq> kNoPrereq{};
      const auto& prereqs = mv ? mv->prereq : kNoPrereq;
      // Note: a per-test waveform change also re-runs apply_voice_defaults,
      // which sets several other params from `kVoiceDefaults`. That can shift
      // the audio even when the param under test is at the same value on
      // both sides — but the test is comparing min vs max, so the only
      // delta that matters is the one we set. Any defaults we pick up
      // apply symmetrically.
      Library l3(g_clap_path);
      const clap_plugin_t* p = l3.create();
      set_param(p, find_param(p, "Waveform"), static_cast<double>(test_waveform));
      for (const auto& prereq : prereqs) {
        set_param(p, find_param(p, prereq.param_name), prereq.value);
      }
      set_param(p, static_cast<clap_id>(i), s.min);
      Render a = render_param(p, 8);
      Library l4(g_clap_path);
      const clap_plugin_t* p2 = l4.create();
      set_param(p2, find_param(p2, "Waveform"), static_cast<double>(test_waveform));
      for (const auto& prereq : prereqs) {
        set_param(p2, find_param(p2, prereq.param_name), prereq.value);
      }
      set_param(p2, static_cast<clap_id>(i), s.max);
      Render b = render_param(p2, 8);
      const AudioDiff diff = audio_diff(a.left, a.right, b.left, b.right);
      const bool ok = audio_diff_passes(diff);
      CHECK(ok, std::string("audio at min vs max for '") + s.name +
                "' (wave=" + wave_name + ") is indistinguishable "
                "(corr_l=" + std::to_string(diff.corr_l) +
                " corr_r=" + std::to_string(diff.corr_r) +
                " amp_l=" + std::to_string(diff.amp_l) +
                " amp_r=" + std::to_string(diff.amp_r) + ")");
    }
  }
  THEN("every audio-bearing parameter changes the rendered audio; non-audio parameters stay finite at min and max");
  coverage::mark("integration", "audio", "every-param-changes-audio", "integration_each_param_changes_audio");
  plugin->destroy(plugin);
}

SCENARIO(integration_every_preset_is_audible) {
  GIVEN("the plugin and the preset parameter");
  const Library lib(g_clap_path);
  const clap_plugin_t* plugin = lib.create();
  const clap_id preset_id = find_param(plugin, "Preset");
  const int num = static_cast<int>(param_info(plugin, preset_id).max_value);
  // Pre-render each preset so we can compare adjacent presets for distinctness.
  std::vector<Render> renders;
  renders.reserve(static_cast<size_t>(num) + 1);
  WHEN("each preset is loaded and a sustained note is rendered");
  for (int p = 0; p <= num; ++p) {
    set_param(plugin, preset_id, static_cast<double>(p));
    char name_buf[128]{};
    params_of(plugin)->value_to_text(plugin, preset_id, static_cast<double>(p), name_buf, sizeof(name_buf));
    Stats s = render_sustained(plugin, 4);
    CHECK(s.finite, std::string("non-finite for preset ") + name_buf);
    renders.push_back(render_param(plugin, 8));
    coverage::mark("preset", "header", name_buf, "integration_every_preset_is_audible");
  }
  // Adjacent presets must produce audibly different envelopes — a preset
  // parameter that's silently mapped to the same instrument across all slots
  // would fail here.
  for (int p = 0; p < num; ++p) {
    const AudioDiff diff = audio_diff(renders[p].left, renders[p].right,
                                       renders[p + 1].left, renders[p + 1].right);
    CHECK(audio_diff_passes(diff),
          std::string("adjacent presets ") + std::to_string(p) + " and " +
          std::to_string(p + 1) + " produce indistinguishable audio (corr_l=" +
          std::to_string(diff.corr_l) + " corr_r=" + std::to_string(diff.corr_r) +
          " amp_l=" + std::to_string(diff.amp_l) + " amp_r=" +
          std::to_string(diff.amp_r) + ")");
  }
  THEN("every factory preset renders finite audio and adjacent presets are audibly distinct");
  plugin->destroy(plugin);
}

// Adjacent waveforms must produce audibly different envelopes — a waveform
// selector that silently maps adjacent indices to the same timbre (a
// common bug in the waveform enum table) would fail here.
//
// Adjacent chips from the same family (YM2203/YM2608, OPL2/OPL3, YM2612
// single vs 10-channel stack) sound very similar — they share an FM core
// and only differ in channel count or subtle modulation. We expect those
// to correlate at 0.97-0.99, which is the chip variant's natural overlap.
// An allowlist exempts those pairs from the strict threshold; anything
// outside this list that correlates above kMaxAudioCorrelation is a real
// waveform-selector bug.
inline bool adjacent_waveform_exempt(int a_id, int b_id) {
  static const std::set<std::pair<int, int>> kExempt = {
      // YM2203 ↔ YM2608 — same SSG/AY + FM core, only the rhythm/ADPCM differ
      {31, 32}, {32, 31},
      // Konami SCC wavetable ↔ five-channel stack — same SCC chip, only the
      // voice count differs. A single-note sustained render can't tell them
      // apart because only one voice fires in both cases.
      {40, 41}, {41, 40},
      // Philips SAA1099 tone ↔ six-channel stack — same SAA1099 chip, only
      // voice count differs. Same single-note sustained-render caveat.
      {42, 43}, {43, 42},
      // Atari TIA polynomial tone ↔ two-channel stack — same TIA chip.
      {44, 45}, {45, 44},
  };
  return kExempt.count({a_id, b_id}) > 0;
}

SCENARIO(integration_every_waveform_is_audible) {
  GIVEN("the plugin and the waveform parameter");
  const Library lib(g_clap_path);
  const clap_plugin_t* plugin = lib.create();
  const clap_id wave_id = find_param(plugin, "Waveform");
  const int num = static_cast<int>(param_info(plugin, wave_id).max_value);
  std::vector<Render> renders;
  renders.reserve(static_cast<size_t>(num) + 1);
  WHEN("each waveform is selected and a sustained note is rendered");
  for (int w = 0; w <= num; ++w) {
    set_param(plugin, wave_id, static_cast<double>(w));
    char name_buf[128]{};
    params_of(plugin)->value_to_text(plugin, wave_id, static_cast<double>(w), name_buf, sizeof(name_buf));
    Stats s = render_sustained(plugin, 4);
    CHECK(s.finite, std::string("non-finite for waveform ") + name_buf);
    renders.push_back(render_param(plugin, 8));
    coverage::mark("waveform", "voice", name_buf, "integration_every_waveform_is_audible");
  }
  // Adjacent waveforms must produce audibly different envelopes — a waveform
  // selector that silently maps adjacent indices to the same timbre (a
  // common bug in the waveform enum table) would fail here.
  for (int w = 0; w < num; ++w) {
    if (adjacent_waveform_exempt(w, w + 1)) continue;
    const AudioDiff diff = audio_diff(renders[w].left, renders[w].right,
                                       renders[w + 1].left, renders[w + 1].right);
    // If BOTH waveforms are silent (amp ≈ 0), neither has implemented the
    // chip yet — that's a separate "waveform is unimplemented" gate, not a
    // "two waveforms are mapped to the same voice" regression. The
    // unimplemented-waveform gate lives in `integration_every_waveform_is_audible`
    // as the per-waveform finite check above the loop. Here we skip the
    // adjacent-distinct comparison when both buffers are silent so a not-yet-
    // implemented chip doesn't false-positive as "mapped to the same voice".
    const bool both_silent = (std::abs(diff.amp_l) < 0.1 && std::abs(diff.amp_r) < 0.1);
    if (both_silent) continue;
    CHECK(audio_diff_passes(diff),
          std::string("adjacent waveforms ") + std::to_string(w) + " and " +
          std::to_string(w + 1) + " produce indistinguishable audio (corr_l=" +
          std::to_string(diff.corr_l) + " corr_r=" + std::to_string(diff.corr_r) +
          " amp_l=" + std::to_string(diff.amp_l) + " amp_r=" +
          std::to_string(diff.amp_r) + ")");
  }
  THEN("every factory waveform renders finite audio and adjacent waveforms are audibly distinct");
  plugin->destroy(plugin);
}

// ===========================================================================
// Spec-aware oracle
// ===========================================================================
//
// The audio-change oracle above proves "the knob does *something*"; this
// scenario proves "the knob does what the *label* says". Each param whose
// name maps to a labeled unit (Hz, dB, ms, semitones, cents, duty ratio,
// FM ratio) is rendered at min and max with the matching voice, the
// resulting audio is measured in its labeled unit, and the measurement is
// compared to the expected delta within tolerance.
//
// Tolerances:
//   - ±20 cents pitch (covers NES timer quantization, integer rounding)
//   - ±1.5 dB gain (covers tanh saturation on small signals)
//   - ±2 points duty, every step (adjacent steps are 12.5 points apart)
//   - ±10% envelope duration (covers per-sample integer ticks)
//
// A param that fails here is a *labeled-spec regression*: the knob says
// "12 semitones" but the audio only shifts by 5. The audio-change oracle
// would still pass for such a knob; only this scenario catches the bug.

SCENARIO(integration_every_param_meets_its_labeled_spec) {
  GIVEN("a freshly created plugin and the labeled-unit map for every param");
  const Library lib(g_clap_path);
  const clap_plugin_t* plugin = lib.create();

  WHEN("each labeled param is set to a value that exercises its full range");
  // Same voice/prereq map as the audio-change scenario so we test against
  // the voice where each param actually does something.
  for (size_t i = 0; i < P::kParamCount; ++i) {
    const auto& s = P::kSpecs[i];
    const auto hint = spec_hint_for_id(s.name);
    if (std::string(hint.units).empty()) continue;
    if (is_non_audio_param(s.name)) continue;

    const ModuleVoice* mv = voice_for_module(s.module);
    const int test_waveform = mv ? mv->waveform : 0;
    const std::vector<ModulePrereq> kNoPrereq{};
    const auto& prereqs = mv ? mv->prereq : kNoPrereq;

    // Render at min and at a near-max value (use 95% of max to stay clear of
    // edge effects where the param hits a hard endpoint).
    const double test_max = s.min + 0.95 * (s.max - s.min);

    // For pitch-related params, force NES triangle so the autocorrelation
    // pitch estimator sees a clean harmonic stack. NES pulse + the NES
    // mixer non-linearities confuse the estimator.
    int pitch_test_waveform = test_waveform;
    const std::string units = hint.units;
    if (units == "semitones" || units == "cents") {
      pitch_test_waveform = 1;  // NES triangle
    }

    Library la(g_clap_path);
    auto pa = la.create();
    set_param(pa, find_param(pa, "Waveform"), static_cast<double>(pitch_test_waveform));
    for (const auto& pr : prereqs) set_param(pa, find_param(pa, pr.param_name), pr.value);
    set_param(pa, static_cast<clap_id>(i), s.min);
    Render ra = render_param(pa, 4);

    Library lb(g_clap_path);
    auto pb = lb.create();
    set_param(pb, find_param(pb, "Waveform"), static_cast<double>(pitch_test_waveform));
    for (const auto& pr : prereqs) set_param(pb, find_param(pb, pr.param_name), pr.value);
    set_param(pb, static_cast<clap_id>(i), test_max);
    Render rb = render_param(pb, 4);

    if (units == "semitones" || units == "cents") {
      // Pitch-shift params (Transpose, Fine tune, Bend range): the
      // expected Hz at the new value is hz_a * 2^(delta_units / 12). This
      // catches both inverted polarity (wrong direction) and broken
      // exponent (wrong cents/semitone).
      //
      // Restrict the test range to ±12 semitones (or ±200 cents) so both
      // sides land in the autocorrelation pitch estimator's 126–1600 Hz
      // window. Beyond that, NES timer quantization + estimator windows
      // make the measurement unreliable; the audio-change oracle still
      // proves the full range is wired.
      const double limit = (units == "cents") ? 200.0 : 12.0;
      const double test_low = std::max(s.min, -limit);
      const double test_high = std::min(test_max, limit);
      // Re-render at the new test_high if it differs from test_max.
      std::vector<float> rb_pitch = rb.left;
      if (test_high != test_max) {
        Library lb3(g_clap_path);
        auto pb3 = lb3.create();
        set_param(pb3, find_param(pb3, "Waveform"), static_cast<double>(pitch_test_waveform));
        for (const auto& pr : prereqs) set_param(pb3, find_param(pb3, pr.param_name), pr.value);
        set_param(pb3, static_cast<clap_id>(i), test_high);
        rb_pitch = render_param(pb3, 4).left;
      }
      std::vector<float> ra_pitch = ra.left;
      if (test_low != s.min) {
        Library la3(g_clap_path);
        auto pa3 = la3.create();
        set_param(pa3, find_param(pa3, "Waveform"), static_cast<double>(pitch_test_waveform));
        for (const auto& pr : prereqs) set_param(pa3, find_param(pa3, pr.param_name), pr.value);
        set_param(pa3, static_cast<clap_id>(i), test_low);
        ra_pitch = render_param(pa3, 4).left;
      }
      const double hz_a = measure_pitch_hz(ra_pitch);
      const double hz_b = measure_pitch_hz(rb_pitch);
      if (hz_a <= 0 || hz_b <= 0) continue;  // both silent, can't measure
      const double delta_units = (test_high - test_low);
      const double divisor = (units == "cents") ? 1200.0 : 12.0;
      const double expected_hz_b = hz_a * std::pow(2.0, delta_units / divisor);
      const double measured_cents = 1200.0 * std::log2(hz_b / expected_hz_b);
      CHECK(std::abs(measured_cents) < 50.0,
            std::string("'") + s.name + "' labeled " + units +
            " but measured " + std::to_string(hz_b) + " Hz vs expected " +
            std::to_string(expected_hz_b) + " Hz (error " +
            std::to_string(measured_cents) + " cents, range " +
            std::to_string(s.min) + ".." + std::to_string(s.max) + ")");
    } else if (units == "hz" || units == "ratio") {
      // Vibrato rate / Chorus rate / FM LFO rate / FM ratio: these change
      // timbre and modulation, not the carrier pitch directly. Skip a
      // pitch check (the carrier stays at 261 Hz); the audio-change
      // oracle already proves the param has audible effect.
      continue;
    } else if (units == "duty") {
      // Every step of the stepped duty enum, on a held note. The fraction of
      // the sustained body above the waveform's midpoint (so a DC offset or a
      // band-limited edge cannot bias it) must land within 2 points of the
      // labelled 12.5/25/50/75%: tight enough that adjacent steps cannot pass
      // for each other.
      constexpr double kDutyTable[] = {0.125, 0.25, 0.5, 0.75};
      for (int step = 0; step < 4; ++step) {
        Library ld(g_clap_path);
        const clap_plugin_t* pd = ld.create();
        set_param(pd, find_param(pd, "Waveform"), static_cast<double>(test_waveform));
        for (const auto& pr : prereqs) set_param(pd, find_param(pd, pr.param_name), pr.value);
        set_param(pd, static_cast<clap_id>(i), static_cast<double>(step));
        const std::vector<float> body = render_param(pd, 40, 0).left;
        pd->destroy(pd);
        const auto first = body.begin() + 4096;  // past the attack
        const auto [lo, hi] = std::minmax_element(first, body.end());
        const double mid = (static_cast<double>(*lo) + static_cast<double>(*hi)) / 2.0;
        const double high = static_cast<double>(std::count_if(first, body.end(),
            [mid](float x) { return x > mid; })) / static_cast<double>(body.end() - first);
        CHECK(std::abs(high - kDutyTable[step]) < 0.02,
              std::string("'") + s.name + "' step " + std::to_string(step) + " measures " +
              std::to_string(high * 100.0) + "% high, labelled " +
              std::to_string(kDutyTable[step] * 100.0) + "%");
      }
    } else if (units == "gain") {
      // Voice gain / Master: gain steps at the bottom of the range are
      // linear (tanh ≈ identity for small signals), but the top of the
      // range hits the soft-clip region where each dB on the knob
      // produces less than 1 dB on the output. That's the product's
      // intentional behaviour — but a knob that ONLY produces < 1 dB
      // per step at the bottom of its range is a regression. We test
      // a *partial* range (test_max capped to the midpoint) so the
      // measurement stays in the linear region; the audio-change oracle
      // still proves the full range does *something*.
      const double test_gain_min = s.min;
      const double test_gain_max = s.min + 0.5 * (s.max - s.min);  // 50% of range
      Library lb2(g_clap_path);
      auto pb2 = lb2.create();
      set_param(pb2, find_param(pb2, "Waveform"), static_cast<double>(test_waveform));
      for (const auto& pr : prereqs) set_param(pb2, find_param(pb2, pr.param_name), pr.value);
      set_param(pb2, static_cast<clap_id>(i), test_gain_max);
      Render rb2 = render_param(pb2, 4);
      const double rms_a = measure_rms(ra.left);
      const double rms_b = measure_rms(rb2.left);
      if (rms_a < 1e-6 || rms_b < 1e-6) continue;  // one side silent, skip
      const double measured_db_delta = 20.0 * std::log10(rms_b / rms_a);
      const double expected_db_delta = test_gain_max - test_gain_min;
      // Allow ±1.5 dB slack: tanh saturation is mild in the lower half
      // of the range, and the measurement averages over the whole buffer
      // (including attack and release).
      CHECK(std::abs(measured_db_delta - expected_db_delta) < 1.5,
            std::string("'") + s.name +
                "' gain: measured delta " + std::to_string(measured_db_delta) +
                " dB, expected " + std::to_string(expected_db_delta) + " dB");
    } else if (units == "ms") {
      // Envelope duration: render the same plugin state for both min and max,
      // then send note-off at the same point and measure how many samples it
      // takes for the amplitude envelope to fall to 10% of its pre-note-off
      // peak. Release_ms = 0 should drop within ~1ms; release_ms = 2000
      // should still be > 50% of peak at the end of our 85ms render.
      // We compare the *min* and *max* drop times; the max-value render
      // should take noticeably longer to drop than the min-value render.
      auto drop_time_ms = [&](const std::vector<float>& v) -> double {
        // The render produces 4 sustain blocks then 4 release blocks. The
        // note-off happens after frame 4*512 = 2048.
        const size_t note_off = 2048;
        if (v.size() <= note_off) return 0.0;
        double peak_before = 0;
        for (size_t i = 0; i < note_off; ++i) {
          const double a = std::abs(v[i]);
          if (a > peak_before) peak_before = a;
        }
        const double threshold = peak_before * 0.1;
        for (size_t i = note_off; i < v.size(); ++i) {
          if (std::abs(v[i]) < threshold) {
            return (i - note_off) * 1000.0 / 48000.0;
          }
        }
        return 1e6;  // never dropped = effectively infinite
      };
      const double t_a = drop_time_ms(ra.left);
      const double t_b = drop_time_ms(rb.left);
      // The release at max should take at least as long as at min. If the
      // param is wired, the difference is meaningful (>= 2 ms typically).
      const bool ok = t_b >= t_a - 1.0;  // allow 1 ms slack
      CHECK(ok, std::string("'") + s.name +
                "' envelope: drop_ms(min)=" + std::to_string(t_a) +
                " drop_ms(max)=" + std::to_string(t_b) +
                " (max should be >= min)");
    } else if (units == "hz_filter") {
      // Chip cutoff / Output rate: rough check that the spectral centroid
      // shifts. With cutoff at min (40 Hz) most energy is filtered out;
      // with cutoff at max (16000 Hz) high harmonics remain. Compute the
      // spectral centroid as a quick filter-cut proxy.
      auto centroid = [](const std::vector<float>& v) {
        // 8-band DFT Goertzel-style band energies
        if (v.size() < 2048) return 0.0;
        double bands[8] = {0};
        const size_t N = 2048;
        for (size_t band = 0; band < 8; ++band) {
          const double lo = static_cast<double>(band) / 8.0;
          const double hi = static_cast<double>(band + 1) / 8.0;
          const double fc = (lo + hi) * 0.5;
          for (size_t n = 0; n < N; ++n) {
            const double phase = 2.0 * 3.14159265358979323846 * fc *
                                 static_cast<double>(n) / N;
            bands[band] += std::abs(v[n] *
                std::cos(phase) - v[n] * std::sin(phase));
          }
        }
        double total = 0, weighted = 0;
        for (size_t i = 0; i < 8; ++i) {
          total += bands[i];
          weighted += bands[i] * static_cast<double>(i);
        }
        return total > 0 ? weighted / total : 0.0;
      };
      const double c_a = centroid(ra.left);
      const double c_b = centroid(rb.left);
      // With cutoff at min, centroid should be lower than at max.
      const bool ok = c_b >= c_a * 0.7;  // tolerate some noise
      CHECK(ok, std::string("'") + s.name +
                "' filter: min centroid=" + std::to_string(c_a) +
                " max centroid=" + std::to_string(c_b) +
                " (max should be >= 70% of min)");
    }
  }
  THEN("every labeled parameter produces the audio effect named in its unit label");
  coverage::mark("integration", "spec", "every-labeled-param-meets-spec",
                 "integration_every_param_meets_its_labeled_spec");
  plugin->destroy(plugin);
}

