SCENARIO(unit_every_param_has_valid_spec) {
  GIVEN("the parameter table in params.hpp");
  std::set<int> seen;
  for (size_t i = 0; i < P::kParamCount; ++i) {
    const auto& s = P::kSpecs[i];
    CHECK(!seen.count(static_cast<int>(i)), "duplicate id");
    seen.insert(static_cast<int>(i));
    CHECK(s.min < s.max, std::string("range min >= max for ") + s.name);
    CHECK(s.def >= s.min - 1e-9 && s.def <= s.max + 1e-9,
          std::string("default out of range for ") + s.name);
    CHECK(s.name && std::strlen(s.name) > 0, "empty name");
    CHECK(s.module && std::strlen(s.module) > 0, "empty module");
  }
  THEN("every spec is internally consistent");
  coverage::mark("param", "table", "every-spec-valid", "unit_every_param_has_valid_spec");
}

